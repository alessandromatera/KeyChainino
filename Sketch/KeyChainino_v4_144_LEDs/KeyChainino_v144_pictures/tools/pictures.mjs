/* ---------- shapes ---------- */

/* Geometric figures are computed, not hand-drawn: pixel centres inside the
   true shape. Each one draws its outline clockwise from the top, fills in,
   then does a trick. */
const inPoly = (pts, x, y) => {
  let inside = false;
  for (let i = 0, j = pts.length - 1; i < pts.length; j = i++) {
    const [xi, yi] = pts[i], [xj, yj] = pts[j];
    if ((yi > y) !== (yj > y) && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) inside = !inside;
  }
  return inside;
};
const regular = (n, r, cx, cy, rotDeg) => Array.from({ length: n }, (_, k) => {
  const a = ((rotDeg + (360 * k) / n) * Math.PI) / 180;
  return [cx + r * Math.cos(a), cy + r * Math.sin(a)];
});
const polygon = pts => grid((x, y) => inPoly(pts, x + 0.5, y + 0.5));
const outlineOf = rows => grid((x, y) => rows[y][x] === '#' &&
  [[1, 0], [-1, 0], [0, 1], [0, -1]].some(([dx, dy]) => rows[y + dy]?.[x + dx] !== '#'));
/* the outline appearing in `parts` steps, clockwise from 12 o'clock */
function tracing(rows, parts) {
  const out = outlineOf(rows), pts = [];
  let cx = 0, cy = 0, n = 0;
  rows.forEach((r, y) => [...r].forEach((c, x) => { if (c === '#') { cx += x; cy += y; n++; } }));
  cx /= n; cy /= n;
  out.forEach((r, y) => [...r].forEach((c, x) => {
    if (c === '#') pts.push({ x, y, a: (Math.atan2(y - cy, x - cx) + 2.5 * Math.PI) % (2 * Math.PI) });
  }));
  pts.sort((p, q) => p.a - q.a);
  return Array.from({ length: parts }, (_, k) => {
    const shown = pts.slice(0, Math.ceil(((k + 1) * pts.length) / parts));
    return grid((x, y) => shown.some(p => p.x === x && p.y === y));
  });
}
function addShape(id, name, filled, trick) {
  const trace = tracing(filled, 6);
  add(id, name, 'shapes', [filled, outlineOf(filled), ...trace], [
    ...trace.map((_, k) => f(2 + k, 110)), f(1, 350), f(0, 250), f(1, 200), f(0, 350), fx(trick),
  ]);
}

