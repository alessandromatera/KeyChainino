/* Generic effects, in the order the firmware cycles through them for the
   child's own drawings. Names must match show.cpp's FX_* ids. */
export const FX = ['hop', 'jelly', 'sparkle', 'wave', 'flip', 'beat', 'burst', 'spin'];

/* ── helpers ─────────────────────────────────────────────────────────── */

export function art(s) {
  const rows = s.trim().split('\n').map(r => r.trim());
  if (rows.length !== 12) throw new Error(`art needs 12 rows, got ${rows.length}:\n${s}`);
  for (const r of rows) {
    if (r.length !== 12 || /[^#.]/.test(r)) throw new Error(`bad art row "${r}" in:\n${s}`);
  }
  return rows;
}

/* copy of `base` with some rows replaced: edit(base, { 3: '#..##......#' }) */
const edit = (base, rows) => base.map((r, y) => (rows[y] !== undefined ? art1(rows[y]) : r));
const art1 = r => {
  if (r.length !== 12 || /[^#.]/.test(r)) throw new Error(`bad row "${r}"`);
  return r;
};

/* union of frames (each may be shifted) */
const over = (...layers) => {
  const out = Array.from({ length: 12 }, () => Array(12).fill('.'));
  for (const l of layers) {
    const [rows, dx = 0, dy = 0] = Array.isArray(l[0]) ? l : [l];
    rows.forEach((r, y) => [...r].forEach((c, x) => {
      const X = x + dx, Y = y + dy;
      if (c === '#' && X >= 0 && X < 12 && Y >= 0 && Y < 12) out[Y][X] = '#';
    }));
  }
  return out.map(r => r.join(''));
};
const shifted = (rows, dx, dy) => over([rows, dx, dy]);
const blank = () => Array(12).fill('............');

/* frame from a predicate */
const grid = fn => Array.from({ length: 12 }, (_, y) =>
  Array.from({ length: 12 }, (_, x) => (fn(x, y) ? '#' : '.')).join(''));

export const f = (frame, ms, o = {}) => ({ frame, ms, dx: o.dx | 0, dy: o.dy | 0,
  dim: !!o.dim, mirror: !!o.mirror });
export const fx = name => {
  if (!FX.includes(name)) throw new Error(`unknown fx ${name}`);
  return { fx: name };
};
const rep = (n, ...steps) => Array.from({ length: n }, () => steps).flat(2);

/* glide frame(s) from (x0,y0) to (x1,y1), one pixel per step; `frames`
   may be a list cycled along the way (walking legs, flapping wings) */
const glide = (frames, [x0, y0], [x1, y1], ms, o = {}) => {
  const fr = [].concat(frames);
  const n = Math.max(Math.abs(x1 - x0), Math.abs(y1 - y0));
  const out = [];
  for (let i = 0; i <= n; i++) {
    out.push(f(fr[i % fr.length], ms, { ...o,
      dx: Math.round(x0 + ((x1 - x0) * i) / (n || 1)),
      dy: Math.round(y0 + ((y1 - y0) * i) / (n || 1)) }));
  }
  return out;
};
/* a hop of height h (up then down) in 2h+1 steps */
const hop = (frame, h, ms, o = {}) => {
  const ys = [];
  for (let i = 0; i <= h; i++) ys.push(-i);
  for (let i = h - 1; i >= 0; i--) ys.push(-i);
  return ys.map(dy => f(frame, ms, { ...o, dy }));
};

