/*
 * pictures.mjs — the built-in picture library: the single source for both
 * the firmware (tools/build.mjs -> pictures_data.cpp) and the web page's
 * sticker gallery.
 *
 * Every picture is 12x12: '#' = LED on, '.' = off. Row 0 is the top row,
 * column 0 the left one (as seen from the front of the KeyChainino).
 * frames[0] is the still picture; the others exist for its animation.
 *
 * anim is the little show A+B plays: a list of steps
 *   f(frame, ms, { dx, dy, dim, mirror })  show a frame, offset/flipped
 *   fx(name)                               run one of the generic effects
 * Helpers below build the repetitive bits (repeats, glides).
 * Durations are rounded to 10 ms, max 2550 ms per step.
 */

/* The built-ins a freshly installed KeyChainino shows (the grown-ups'
   editor on the web page changes the choice; everything else stays in
   flash, one tap away). */
