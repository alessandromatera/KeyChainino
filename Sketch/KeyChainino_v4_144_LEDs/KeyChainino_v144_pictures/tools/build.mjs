/*
 * build.mjs — turn tools/pictures.mjs into firmware data, compile the
 * sketch, and embed both into the web page.
 *
 *   node tools/build.mjs              generate + compile + embed
 *   node tools/build.mjs --gen-only   just rewrite pictures_data.{h,cpp}
 *
 * Steps:
 *   1. pictures_data.h/.cpp   PROGMEM frames, picture table, animation
 *                             steps, effect ids (never edit by hand)
 *   2. arduino-cli compile    -> build/pictures/ in the workspace that
 *                             holds this repo (or the temp dir)
 *   3. upload/keychainino-pictures.html: rewrites the blocks between
 *      LIB_BEGIN/LIB_END (sticker library) and FW_BEGIN/FW_END (firmware
 *      image, base64), so the page stays one self-contained file.
 */
import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import crypto from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { PICTURES, FX, ON_DEVICE_AT_START } from './pictures.mjs';

const HERE = path.dirname(new URL(import.meta.url).pathname);
const SKETCH = path.resolve(HERE, '..');
const PAGE = path.join(SKETCH, 'upload', 'keychainino-pictures.html');
/* the folder holding the KeyChainino repo, next to build/ and simulator/ */
const WORKSPACE = path.resolve(SKETCH, '../../../..');
const OUT_DIR = fs.existsSync(path.join(WORKSPACE, 'build'))
  ? path.join(WORKSPACE, 'build', 'pictures')
  : path.join(os.tmpdir(), 'keychainino-pictures-build');
const FQBN = 'arduino:avr:pro:cpu=8MHzatmega328';
const HEX = path.join(OUT_DIR, 'KeyChainino_v144_pictures.ino.hex');

/* Every picture keeps a permanent number (uid) for life: the KeyChainino
   remembers which built-ins it shows by uid, so adding or reordering
   pictures in pictures.mjs never scrambles a device's choice. New ids get
   the next free number; numbers are never reused. Commit uids.json. */
const UIDS_FILE = path.join(HERE, 'uids.json');
const uids = fs.existsSync(UIDS_FILE) ? JSON.parse(fs.readFileSync(UIDS_FILE, 'utf8')) : {};
let nextUid = Math.max(-1, ...Object.values(uids)) + 1;
for (const p of PICTURES) if (!(p.id in uids)) uids[p.id] = nextUid++;
if (nextUid > 256) throw new Error('out of picture uids (the device keeps a 256-bit choice)');
fs.writeFileSync(UIDS_FILE, JSON.stringify(Object.fromEntries(
  Object.entries(uids).sort((a, b) => a[1] - b[1])), null, 1) + '\n');
for (const id of ON_DEVICE_AT_START) if (!PICTURES.some(p => p.id === id)) throw new Error(`ON_DEVICE_AT_START: no picture ${id}`);
const defaultChoice = new Array(32).fill(0);
for (const id of ON_DEVICE_AT_START) defaultChoice[uids[id] >> 3] |= 1 << (uids[id] & 7);

const STEP_FRAME = 0x1F, STEP_DIM = 0x20, STEP_MIRROR = 0x40, STEP_FX = 0x80;

/* ── 1. encode ───────────────────────────────────────────────────────── */

const rowsOf = frame => frame.map(r => [...r].reduce((w, c, x) => w | (c === '#' ? 1 << x : 0), 0));

const frames = [];   // flat pool of 12-word frames
const pics = [];     // { id, name, group, frame, step, nsteps }
const steps = [];    // [b0, dx, dy, dur10]

for (const p of PICTURES) {
  if (p.frames.length > STEP_FRAME + 1) throw new Error(`${p.id}: too many frames`);
  if (!p.anim.length) throw new Error(`${p.id}: empty animation`);
  const base = frames.length;
  p.frames.forEach(fr => frames.push(rowsOf(fr)));
  const first = steps.length;
  for (const s of p.anim) {
    if (s.fx) { steps.push([STEP_FX | FX.indexOf(s.fx), 0, 0, 0]); continue; }
    if (s.frame >= p.frames.length) throw new Error(`${p.id}: step uses frame ${s.frame}`);
    const d = Math.round(s.ms / 10);
    if (d < 1 || d > 255) throw new Error(`${p.id}: step of ${s.ms} ms out of range`);
    if (Math.abs(s.dx) > 127 || Math.abs(s.dy) > 127) throw new Error(`${p.id}: offset out of range`);
    steps.push([s.frame | (s.dim ? STEP_DIM : 0) | (s.mirror ? STEP_MIRROR : 0),
      s.dx & 0xFF, s.dy & 0xFF, d]);
  }
  if (steps.length - first > 255) throw new Error(`${p.id}: more than 255 steps`);
  pics.push({ id: p.id, uid: uids[p.id], name: p.name, group: p.group, frame: base, step: first, nsteps: steps.length - first });
}
if (frames.length > 255) throw new Error('more than 255 frames in total');
if (pics.length > 200) throw new Error('too many pictures: the list index is a byte');

/* ── 2. firmware data ────────────────────────────────────────────────── */

const hex3 = v => '0x' + v.toString(16).toUpperCase().padStart(3, '0');
const hex2 = v => '0x' + v.toString(16).toUpperCase().padStart(2, '0');
const banner = '/* GENERATED by tools/build.mjs from tools/pictures.mjs — do not edit. */\n';

const header = banner + `#ifndef PICTURES_DATA_H
#define PICTURES_DATA_H

#include <Arduino.h>

#define NUM_BUILTIN ${pics.length}
#define NUM_FRAMES ${frames.length}
#define NUM_STEPS ${steps.length}

/* generic effects (show.cpp), in the order drawings cycle through them */
${FX.map((n, i) => `#define FX_${n.toUpperCase()} ${i}`).join('\n')}
#define NUM_FX ${FX.length}

/* animation step: { frame | flags, dx, dy, duration in 10ms units } */
#define STEP_FRAME 0x${STEP_FRAME.toString(16)}
#define STEP_DIM 0x${STEP_DIM.toString(16)}
#define STEP_MIRROR 0x${STEP_MIRROR.toString(16)}
#define STEP_FX 0x${STEP_FX.toString(16)}  /* run effect (frame field = FX id) */

struct PicDef {
  uint16_t step;   // first animation step in STEPS
  uint8_t frame;   // still picture in FRAMES; animation frames follow it
  uint8_t nsteps;
  uint8_t uid;     // permanent picture number (tools/uids.json)
};

extern const uint16_t FRAMES[NUM_FRAMES][12] PROGMEM;
/* "KCP-BUILD " + 16 hex digits fingerprinting this firmware's sources: the
   web page reads just these bytes to know whether the KeyChainino has
   exactly its program (instead of comparing kilobytes of flash) */
extern const char BUILD_ID[] PROGMEM;
/* which built-ins a fresh KeyChainino shows: bit (uid & 7) of byte uid/8 */
extern const uint8_t DEFAULT_CHOICE[32] PROGMEM;
extern const PicDef PICS[NUM_BUILTIN] PROGMEM;
extern const uint8_t STEPS[NUM_STEPS][4] PROGMEM;

#endif
`;

let src = banner + '#include "pictures_data.h"\n\nconst uint16_t FRAMES[NUM_FRAMES][12] PROGMEM = {\n';
PICTURES.forEach((p, i) => {
  src += `  /* ${p.id} */\n`;
  p.frames.forEach((_, k) => {
    src += `  {${frames[pics[i].frame + k].map(hex3).join(', ')}},\n`;
  });
});
src += '};\n\nconst PicDef PICS[NUM_BUILTIN] PROGMEM = {\n';
src += pics.map(p => `  {${p.step}, ${p.frame}, ${p.nsteps}, ${p.uid}},  // ${p.id}`).join('\n');
src += '\n};\n\nconst uint8_t STEPS[NUM_STEPS][4] PROGMEM = {\n';
for (let i = 0; i < steps.length; i += 6) {
  src += '  ' + steps.slice(i, i + 6).map(s => `{${s.map(hex2).join(', ')}}`).join(', ') + ',\n';
}
src += '};\n';
src += `\n/* ${ON_DEVICE_AT_START.join(', ')} */\nconst uint8_t DEFAULT_CHOICE[32] PROGMEM = {\n  ` +
  defaultChoice.map(hex2).join(', ') + '\n};\n';

/* the build id: a hash of every source that goes into the firmware (this
   generated data included), so the same sources always give the same id */
const h = crypto.createHash('sha256').update(header).update(src);
for (const f of fs.readdirSync(SKETCH).filter(f => /\.(ino|cpp|h)$/.test(f) && !f.startsWith('pictures_data')).sort()) {
  h.update(f).update(fs.readFileSync(path.join(SKETCH, f)));
}
const buildId = h.digest('hex').slice(0, 16);
src += `\nconst char BUILD_ID[] PROGMEM = "KCP-BUILD ${buildId}";\n`;

fs.writeFileSync(path.join(SKETCH, 'pictures_data.h'), header);
fs.writeFileSync(path.join(SKETCH, 'pictures_data.cpp'), src);
console.log(`build id: ${buildId}`);
console.log(`data: ${pics.length} pictures, ${frames.length} frames (${frames.length * 24} B), ` +
  `${steps.length} steps (${steps.length * 4} B)`);

if (process.argv.includes('--gen-only')) process.exit(0);

/* ── 3. compile ──────────────────────────────────────────────────────── */

fs.mkdirSync(OUT_DIR, { recursive: true });
const log = execFileSync('arduino-cli',
  ['compile', '--fqbn', FQBN, '--output-dir', OUT_DIR, SKETCH], { encoding: 'utf8' });
console.log(log.split('\n').filter(l => /Sketch uses|Global variables/.test(l)).join('\n'));

/* ── 4. embed into the page ─────────────────────────────────────────── */

function parseIntelHex(text) {
  const data = new Map();
  let base = 0, top = 0;
  for (const line of text.split(/\r?\n/)) {
    if (!line.startsWith(':')) continue;
    const rec = Buffer.from(line.slice(1), 'hex');
    const n = rec[0], type = rec[3], off = (rec[1] << 8) | rec[2];
    if (type === 0) for (let i = 0; i < n; i++) { data.set(base + off + i, rec[4 + i]); top = Math.max(top, base + off + i + 1); }
    else if (type === 1) break;
    else if (type === 2) base = ((rec[4] << 8) | rec[5]) << 4;
    else if (type === 4) base = ((rec[4] << 8) | rec[5]) << 16;
  }
  const img = Buffer.alloc(top, 0xFF);
  for (const [a, v] of data) img[a] = v;
  return img;
}

if (!fs.existsSync(PAGE)) {
  console.log(`page not found, nothing embedded: ${PAGE}`);
  process.exit(0);
}

const img = parseIntelHex(fs.readFileSync(HEX, 'utf8'));
const built = new Date().toISOString().slice(0, 10);
const lib = PICTURES.map((p, i) => ({
  id: p.id, uid: uids[p.id], name: p.name, group: p.group,
  frames: p.frames.map((_, k) => frames[pics[i].frame + k]),
  steps: steps.slice(pics[i].step, pics[i].step + pics[i].nsteps),
}));

let html = fs.readFileSync(PAGE, 'utf8');
const put = (tag, body) => {
  const re = new RegExp(`/\\*${tag}_BEGIN\\*/[\\s\\S]*?/\\*${tag}_END\\*/`);
  if (!re.test(html)) throw new Error(`${tag}_BEGIN/${tag}_END block missing in the page`);
  html = html.replace(re, () => `/*${tag}_BEGIN*/\n${body}\n/*${tag}_END*/`);
};
put('LIB', `const FX_NAMES = ${JSON.stringify(FX)};\n` +
  `const ON_DEVICE_AT_START = ${JSON.stringify(ON_DEVICE_AT_START.map(id => uids[id]))};\n` +
  `const LIBRARY = ${JSON.stringify(lib)};`);
put('FW', `const FIRMWARE = { name: "KeyChainino Pictures", file: "${path.basename(HEX)}", ` +
  `built: "${built}", bytes: ${img.length},\n  b64: "${img.toString('base64')}" };`);
fs.writeFileSync(PAGE, html);
console.log(`embedded ${img.length} B firmware + ${lib.length} stickers into ${path.relative(SKETCH, PAGE)}`);
